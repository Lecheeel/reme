def main():
    by_file = collections.defaultdict(list)
    for q in NEW_QUESTIONS:
        by_file[q[0]].append(q)

    all_ids = []
    next_id = 13
    for fname in FILES:
        path = os.path.join(BASE, fname)
        with open(path, encoding='utf-8') as f:
            doc = json.load(f)
        ch = doc['chapter']
        ch_id = ch['id']
        kp_by_id = {kp['id']: kp for kp in ch['knowledge_points']}
        added = 0
        for (cid, kpid, qtype, stem, opts, ans, expl) in by_file.get(ch_id, []):
            qid = f'zz_{next_id:04d}'
            next_id += 1
            kp = kp_by_id[kpid]
            kp.setdefault('questions', []).append({
                'id': qid, 'type': qtype, 'stem': stem,
                'options': [{'label': l, 'text': t} for l, t in opts],
                'answer': ans, 'explanation': expl,
            })
            added += 1
            all_ids.append(qid)
        if added:
            doc['version'] = doc.get('version', 0) + 1
            with open(path, 'w', encoding='utf-8') as f:
                json.dump(doc, f, ensure_ascii=False, indent=2)
                f.write('\n')
        print(f'  {fname}: +{added} 题 (v{doc["version"]})')

    dup = [k for k, v in collections.Counter(all_ids).items() if v > 1]
    print(f'新增 {len(all_ids)} 题 | id 重复: {dup if dup else "无"}')

if __name__ == '__main__':
    main()
